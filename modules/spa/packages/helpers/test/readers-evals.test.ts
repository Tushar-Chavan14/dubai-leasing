/** A reader that answers from the labelled document's own `perfect` answer, found by the "file" it is handed. */
const perfect = (
  docs: { file: string; perfect: Record<string, unknown> }[],
  tweak?: (file: string, a: unknown) => unknown,
) => {
  const by = new Map(docs.map((d) => [d.file, d.perfect]));
  return new FakeLlm(
    () => new Error("no decide"),
    (images) => {
      const file = new TextDecoder().decode(images[0]!);
      const a = by.get(file);
      if (!a) throw new Error("model down");
      return tweak ? tweak(file, a) : a;
    },
  );
};
const readFile = async (file: string) => new TextEncoder().encode(file);
const match = (docNames: string[], sellers: string[]) => {
  const reasons: string[] = [];
  const left = sellers.map((s) => s.toLowerCase());
  if (docNames.length !== sellers.length) reasons.push("count");
  for (const n of docNames) {
    const at = left.indexOf(n.toLowerCase());
    if (at === -1) reasons.push(n);
    else left.splice(at, 1);
  }
  return { matched: !reasons.length, reasons };
};

