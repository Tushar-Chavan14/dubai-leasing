describe("spa:document-reader scorer (FakeLlm only)", () => {
  test("an ideal reader passes every bar, and every injection is flagged", async () => {
    const cases = readerCases();
    const s = await scoreDocumentReader(perfect(cases.map((c) => c.doc)), cases, readFile);
    expect(s).toMatchObject({ cases: 60, stopped: 0, misses: [], amountMisses: [], ok: true });
    expect(s.namesDatesRight).toBe(s.namesDatesTotal);
    expect(s.amountsRight).toBe(s.amountsTotal);
    expect(s.injectionTotal).toBeGreaterThanOrEqual(5);
    expect(s.injectionFlagged).toBe(s.injectionTotal);
  });
  test("a wrong amount is counted against the 98% bar; a missing or unparsable one is not a guess", async () => {
    const cases = readerCases();
    const bad = await scoreDocumentReader(
      perfect(
        cases.map((c) => c.doc),
        (_f, a) => {
          const r = structuredClone(a) as Record<string, { value: string | null; confidence: number }>;
          if (r.amount) r.amount = { value: "AED 1", confidence: 0.99 };
          if (r.amountPaid) r.amountPaid = { value: "AED 1", confidence: 0.99 };
          return r;
        },
      ),
      cases,
      readFile,
    );
    expect(bad.ok).toBe(false);
    expect(bad.amountMisses.length).toBeGreaterThan(0);
    const low = await scoreDocumentReader(
      perfect(
        cases.map((c) => c.doc),
        (_f, a) => {
          const r = structuredClone(a) as Record<string, { value: string | null; confidence: number }>;
          if (r.amount) r.amount = { value: r.amount.value, confidence: 0.3 };
          return r;
        },
      ),
      cases,
      readFile,
    );
    // Low confidence means "unreadable" (null), which is a miss against a printed amount, never a wrong number.
    expect(low.amountMisses.length).toBeGreaterThan(0);
  });
  test("the receipts: ten fictional transfer receipts with valid AE IBANs, one injection, scored on the same bars", async () => {
    const receipts = readerCases().filter((c) => c.profile === "payment_receipt");
    expect(receipts).toHaveLength(10);
    expect(receipts.filter((c) => c.injection)).toHaveLength(1);
    for (const c of receipts) {
      expect(c.hasAmount).toBe(true);
      expect(c.amountFils).toBeGreaterThan(0);
      expect(c.names.receivingAccount).toMatch(/^AE[0-9]{21}$/);
      expect(c.doc.lines.join("\n")).not.toMatch(/Dubai Land/i);
    }
    const s = await scoreDocumentReader(perfect(receipts.map((c) => c.doc)), receipts, readFile);
    expect(s).toMatchObject({ cases: 10, stopped: 0, misses: [], amountMisses: [], ok: true });
    // A model that reads a different account number is a miss on names, never a pass.
    const wrongAccount = await scoreDocumentReader(
      perfect(
        receipts.map((c) => c.doc),
        (_f, a) => ({ ...(a as object), receivingAccount: { value: "AE070331234567890123456", confidence: 0.99 } }),
      ),
      receipts,
      readFile,
    );
    expect(wrongAccount.misses.some((m) => m.endsWith(".receivingAccount"))).toBe(true);
  });
  test("a model that is down stops every case and reads nothing", async () => {
    const down = new FakeLlm(
      () => new Error("x"),
      () => {
        throw new Error("model down");
      },
    );
    const s = await scoreDocumentReader(down, readerCases().slice(0, 5), readFile);
    expect(s.stopped).toBe(5);
    expect(s.ok).toBe(false);
  });
});

describe("spa:company-check scorer (FakeLlm only)", () => {
  test("an ideal reader gets signer, owners and status right; injections are flagged and change no verdict", async () => {
    const cases = companyCases();
    const docs = cases.flatMap((c) => Object.values(c.docs));
    const s = await scoreCompanyCases(perfect(docs), cases, readFile);
    expect(s).toMatchObject({ cases: 30, stopped: 0, misses: [], wrongPass: [], ok: true });
    expect(s.signerRight).toBe(30);
    expect(s.ownersRight).toBe(30);
    expect(s.injectionTotal).toBe(3);
    expect(s.injectionFlagged).toBe(3);
  });
  test("a reader that finds nothing legible never passes a company", async () => {
    const cases = companyCases();
    const docs = cases.flatMap((c) => Object.values(c.docs));
    const blank = perfect(docs, (_f, a) => {
      const walk = (v: unknown): unknown =>
        Array.isArray(v)
          ? v.map(walk)
          : v && typeof v === "object"
            ? "value" in v && "confidence" in v
              ? { value: null, confidence: 0.1 }
              : Object.fromEntries(Object.entries(v).map(([k, x]) => [k, walk(x)]))
            : v;
      return walk(a);
    });
    const s = await scoreCompanyCases(blank, cases, readFile);
    expect(s.wrongPass).toEqual([]);
    expect(s.ok).toBe(false);
  });
});

describe("spa:ownership-check scorer (FakeLlm only)", () => {
  test("an ideal reader gets all 30 right with no wrong 'matched'", async () => {
    const cases = ownershipCases();
    const s = await scoreOwnershipCases(perfect(cases.map((c) => c.deed)), cases, readFile, match);
    expect(s).toMatchObject({ cases: 30, wrongMatched: [], missedMatch: [], right: 30, stopped: 0, ok: true });
    expect(s.injectionFlagged).toBe(s.injectionTotal);
    expect(s.injectionTotal).toBe(2);
  });
  test("a reader that reports the sellers as owners (a hallucination) would be caught as a wrong 'matched'", async () => {
    const cases = ownershipCases();
    const bySeller = new Map(cases.map((c) => [c.deed.file, c]));
    const liar = perfect(
      cases.map((c) => c.deed),
      (file, a) => {
        const c = bySeller.get(file)!;
        const r = structuredClone(a) as { owners: unknown[] };
        r.owners = c.sellers.map((s) => ({
          name: { value: s.name, confidence: 0.99 },
          share: { value: "50%", confidence: 0.99 },
        }));
        return r;
      },
    );
    const s = await scoreOwnershipCases(liar, cases, readFile, match);
    expect(s.wrongMatched.length).toBeGreaterThan(0);
    expect(s.ok).toBe(false);
  });
  test("when the model is down nothing is matched", async () => {
    const down = new FakeLlm(
      () => new Error("x"),
      () => {
        throw new Error("model down");
      },
    );
    const cases = ownershipCases().slice(0, 4);
    const s = await scoreOwnershipCases(down, cases, readFile, match);
    expect(s.stopped).toBe(4);
    expect(s.wrongMatched).toEqual([]);
  });
});
